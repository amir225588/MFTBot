@app.route("/webhook", methods=["POST"])
def webhook():

    data = request.get_json(silent=True) or {}

    text = ""

    try:
        text = data.get("body", "")
    except Exception:
        text = ""

    if text == "/start":
        return jsonify({
            "type": "text",
            "body": WELCOME
        })

    if text == "دپارتمان ها":
        return jsonify({
            "type": "text",
            "body": "\n".join(DEPARTMENTS.keys())
        })

    if text in DEPARTMENTS:
        return jsonify({
            "type": "text",
            "body": DEPARTMENTS[text]
        })

    if text == "تماس":
        return jsonify({
            "type": "text",
            "body": f"☎️ {PHONE}\n🌐 {SITE}"
        })

    return jsonify({
        "type": "text",
        "body": "لطفا از منو استفاده کنید."
    })


